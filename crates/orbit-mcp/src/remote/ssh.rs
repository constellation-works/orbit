//! Shared SSH connection defaults for direct and federated MCP sessions.

use std::fs;
use std::path::Path;
use std::process::Command;

use orbit_common::OrbitError;
use orbit_common::fs::io::{atomic_write_text_volatile, create_private_dir_all};
use orbit_common::fs::path::global_orbit_dir;

/// Build a non-PTY transport, leaving the remote command and stdio to callers.
///
/// A generated SSH config includes the native configs before our defaults:
/// command-line `-o` defaults would override even an explicit user opt-out.
pub(crate) fn ssh_command(target: &str) -> Result<Command, OrbitError> {
    let state = global_orbit_dir()?;
    let sockets = state.join("ssh");
    prepare_socket_dir(&sockets).map_err(|error| {
        OrbitError::Io(format!(
            "prepare SSH socket directory '{}': {error}",
            sockets.display()
        ))
    })?;

    let absolute = sockets.join("%C");
    // %C expands to a 40-byte hash of the SSH connection identity. Count bytes,
    // not Unicode characters. OpenSSH appends a dot plus 16 random bytes when
    // binding its temporary socket; reserve those and the terminating NUL in
    // the portable 104-byte sun_path buffer.
    let short = absolute.as_os_str().as_encoded_bytes().len() - 2 + 40 > 86;
    let control_path = if short { Path::new("%C") } else { &absolute };
    let home = state
        .parent()
        .ok_or_else(|| OrbitError::Io("Orbit state directory has no parent".to_string()))?;
    let config = format!(
        "# Generated by Orbit; edit your SSH config instead.\n\
         Include {}\nHost *\n  Include /etc/ssh/ssh_config\nHost *\n\
           ControlMaster auto\n  ControlPersist 60\n  ControlPath {}\n",
        config_path(&home.join(".ssh/config"))?,
        config_path(control_path)?,
    );
    let config_file = sockets.join(if short {
        "relative.conf"
    } else {
        "absolute.conf"
    });
    if fs::read_to_string(&config_file).ok().as_deref() != Some(&config) {
        atomic_write_text_volatile(&config_file, &config).map_err(|error| {
            OrbitError::Io(format!(
                "write SSH defaults '{}': {error}",
                config_file.display()
            ))
        })?;
    }

    let mut command = Command::new("ssh");
    if short {
        // Unix socket limits apply to the pathname passed to bind/connect,
        // so a relative hash also works with arbitrarily long home paths.
        command.current_dir(&sockets);
    }
    command
        .arg("-T")
        .arg("-F")
        .arg(config_file)
        .arg("--")
        .arg(target);
    Ok(command)
}

fn config_path(path: &Path) -> Result<String, OrbitError> {
    let path = path
        .to_str()
        .filter(|path| !path.contains(['\n', '\r']))
        .ok_or_else(|| {
            OrbitError::InvalidInput(
                "SSH config paths must be UTF-8 without line breaks".to_string(),
            )
        })?;
    // Preserve the one intentional token. Literal percent signs in home paths
    // must not turn into OpenSSH substitutions.
    let escaped = path.replace('\\', "\\\\").replace('"', "\\\"");
    let escaped = if let Some(prefix) = escaped.strip_suffix("%C") {
        format!("{}%C", prefix.replace('%', "%%"))
    } else {
        escaped.replace('%', "%%")
    };
    Ok(format!("\"{escaped}\""))
}

fn prepare_socket_dir(path: &Path) -> std::io::Result<()> {
    create_private_dir_all(path)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::{MetadataExt, OpenOptionsExt, PermissionsExt};
        let directory = fs::OpenOptions::new()
            .read(true)
            .custom_flags(libc::O_NOFOLLOW | libc::O_DIRECTORY)
            .open(path)?;
        let metadata = directory.metadata()?;
        // A control socket lets its owner open authenticated SSH sessions.
        if metadata.uid() != unsafe { libc::geteuid() } {
            return Err(std::io::Error::new(
                std::io::ErrorKind::PermissionDenied,
                "SSH socket directory belongs to another user",
            ));
        }
        if metadata.permissions().mode() & 0o7777 != 0o700 {
            directory.set_permissions(fs::Permissions::from_mode(0o700))?;
        }
    }
    Ok(())
}
