#!/usr/bin/env python3
"""Generate corpus indexes or materialize deterministic task-history appends.

No network, commits, task mutations or merges. Materialization leaves a batch
of repository changes for normal review; replaying a batch is idempotent.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import sys

import yaml

KINDS = {"issue": "issues", "decision": "decisions", "guideline": "guidelines"}
SECTIONS = {
    "issue": ["Signature", "Mechanism", "Resolution", "Fix task", "Occurrences"],
    "decision": ["Scope", "Entries"],
    "guideline": ["Rule", "Rationale", "Escalation"],
}


def corpus_documents(corpus):
    rows = []
    for path in sorted(corpus.rglob("*.md")):
        if path.name == "INDEX.md":
            continue
        if path.is_symlink():
            raise ValueError(f"corpus symlink refused: {path}")
        raw = path.read_text(encoding="utf-8")
        if not raw.startswith("---\n"):
            raise ValueError(f"{path}: frontmatter required")
        frontmatter, delimiter, body = raw[4:].partition("\n---\n")
        if not delimiter:
            raise ValueError(f"{path}: closing frontmatter delimiter required")
        meta = yaml.safe_load(frontmatter)
        if not isinstance(meta, dict):
            raise ValueError(f"{path}: frontmatter must be a mapping")
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*\.md", path.name):
            raise ValueError(f"{path}: filename must be a lowercase mechanism or topic slug")
        kind = meta.get("type")
        relative = path.relative_to(corpus).as_posix()
        if kind not in KINDS or path.parent != corpus / KINDS[kind]:
            raise ValueError(f"{path}: type must match its direct type directory")
        if meta.get("status") not in {"active", "draft", "resolved", "superseded"}:
            raise ValueError(f"{path}: invalid status")
        for key in ("applies_to", "links"):
            if not isinstance(meta.get(key), list) or any(not isinstance(v, str) or not v for v in meta[key]):
                raise ValueError(f"{path}: {key} must be a list of nonempty strings")
        if not meta["applies_to"] or any(not name.replace("_", "a").isascii() or not name.replace("_", "a").isalnum() for name in meta["applies_to"]):
            raise ValueError(f"{path}: invalid applies_to activity")
        title = next((line[2:].strip() for line in body.splitlines() if line.startswith("# ")), None)
        if not title or any(ch in title + relative for ch in "|\r\n<>"):
            raise ValueError(f"{path}: unsafe title or filename")
        headings = [line[3:].strip() for line in body.splitlines() if line.startswith("## ")]
        if any(section not in headings for section in SECTIONS[kind]):
            raise ValueError(f"{path}: expected sections {SECTIONS[kind]}")
        row = {"path": relative, "type": kind, "status": meta["status"],
               "applies_to": sorted(set(meta["applies_to"])), "title": title, "links": meta["links"]}
        if "match_infra_class" in meta:
            if kind != "issue" or meta["match_infra_class"] not in {"lock_busy", "store_locked"}:
                raise ValueError(f"{path}: invalid engine infrastructure match")
            row["match_infra_class"] = meta["match_infra_class"]
        rows.append(row)
    return rows


def generate_index(corpus, check):
    rows = corpus_documents(corpus)
    lines = ["# Workspace agent corpus", "", "Generated by `scripts/agent-corpus.py`; do not edit.",
             "Resolved issues remain here as history and are excluded from activity injection.",
             "", "<!-- agent-corpus-schema: 1 -->", "", "| Document | Type | Status | Activities |",
             "| --- | --- | --- | --- |"]
    for row in rows:
        lines.append(f"| [{row['title']}]({row['path']}) | {row['type']} | {row['status']} | {', '.join(row['applies_to'])} |")
    lines.append("")
    for row in rows:
        # Single-line JSON is the versioned runtime read boundary. Escape HTML
        # delimiters so frontmatter cannot terminate the enclosing comment.
        encoded = json.dumps(row, sort_keys=True, ensure_ascii=True).replace("<", "\\u003c").replace(">", "\\u003e")
        lines.append(f"<!-- agent-corpus-row {encoded} -->")
    expected = "\n".join(lines) + "\n"
    target = corpus / "INDEX.md"
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            raise ValueError(f"{target} is stale; run scripts/agent-corpus.py")
    else:
        target.write_text(expected, encoding="utf-8")
    print(f"{'verified' if check else 'generated'} {target}")


def outbox_records(value):
    """Accept task.show JSON (including a wrapped value), or a batch of them."""
    if isinstance(value, list):
        for item in value:
            yield from outbox_records(item)
    elif isinstance(value, dict):
        if "value" in value:
            yield from outbox_records(value["value"])
        for event in value.get("history", []):
            if event.get("event") == "agent_corpus_append" and event.get("by") == "system":
                yield json.loads(event["note"])


def materialize(repo, corpus, sources):
    proposals = {}
    for source in sources:
        for record in outbox_records(json.loads(source.read_text(encoding="utf-8"))):
            if record.get("schema_version") != 1 or set(record) != {"schema_version", "id", "path", "section", "entry"}:
                raise ValueError("invalid corpus append schema")
            if not isinstance(record["id"], str) or not isinstance(record["entry"], dict):
                raise ValueError("invalid corpus append identity or entry")
            relative = Path(record["path"])
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError("corpus append destination escapes repository")
            target = repo / relative
            if target.is_symlink() or not target.resolve().is_relative_to(corpus.resolve()):
                raise ValueError("corpus append destination escapes corpus")
            kind = {"Occurrences": "issues", "Entries": "decisions"}.get(record["section"])
            if kind is None or target.parent != corpus / kind or target.suffix != ".md":
                raise ValueError("corpus append has invalid section or destination")
            if not target.exists():
                raise ValueError(f"{target}: create and review the topic doc before materializing appends")
            key = record["id"]
            if key in proposals and proposals[key] != record:
                raise ValueError(f"conflicting corpus append {key}")
            proposals[key] = record
    # Validate all destinations before touching any file; changes are one
    # reviewable batch. Source outbox entries are retained indefinitely.
    updates = {}
    for identity, record in sorted(proposals.items()):
        target = repo / record["path"]
        raw = updates.get(target, target.read_text(encoding="utf-8"))
        marker = "<!-- corpus-append:" + hashlib.sha256(identity.encode()).hexdigest() + " -->"
        if marker in raw:
            continue
        heading = "## " + record["section"]
        start = raw.find("\n" + heading + "\n")
        if start < 0:
            raise ValueError(f"{target}: missing {heading}")
        end = raw.find("\n## ", start + len(heading) + 2)
        if end < 0:
            end = len(raw)
        # JSON keeps human text as data; escape fences and HTML delimiters.
        payload = json.dumps(record["entry"], indent=2, sort_keys=True, ensure_ascii=True).replace("`", "\\u0060").replace("<", "\\u003c").replace(">", "\\u003e")
        addition = f"\n{marker}\n```json\n{payload}\n```\n"
        updates[target] = raw[:end].rstrip() + "\n" + addition + raw[end:]
    for target, content in updates.items():
        target.write_text(content, encoding="utf-8")
        print(f"materialized {target.relative_to(repo)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--corpus", default="docs/agents/corpus")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--records", type=Path, action="append", default=[], help="materialize system outbox records from task.show history JSON")
    args = parser.parse_args()
    repo = args.repo_root.resolve()
    corpus = repo / args.corpus
    if not corpus.resolve().is_relative_to(repo) or corpus.is_symlink():
        parser.error("corpus must stay inside the repository")
    try:
        if args.records:
            if args.check:
                parser.error("--check cannot materialize appends")
            corpus_documents(corpus)
            materialize(repo, corpus, args.records)
        generate_index(corpus, args.check)
    except (ValueError, OSError, yaml.YAMLError) as error:
        print(f"agent-corpus: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
