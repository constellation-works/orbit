#!/usr/bin/env python3
"""Exercise the source-style diff gate on seeded Rust fixtures in scratch repositories."""

import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent
WRAPPER = "scripts/check-source-style-diff.py"
IDENTITY = {
    "GIT_AUTHOR_NAME": "fixture",
    "GIT_AUTHOR_EMAIL": "fixture@invalid",
    "GIT_COMMITTER_NAME": "fixture",
    "GIT_COMMITTER_EMAIL": "fixture@invalid",
}
ENV = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
ENV.update(IDENTITY)

CARGO = '[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2024"\n'
LIB = "//! Fixture crate.\n\nmod clean;\n\nmod debt;\n"
NEW = "    pub fn new() -> Self {\n        Self { value: 0 }\n    }\n"
VALUE = "    pub fn value(&self) -> u32 {\n        self.value\n    }\n"
CLEAN = (
    "pub struct Counter {\n    value: u32,\n}\n\n"
    f"impl Counter {{\n{NEW}\n{VALUE}}}\n\n"
    "pub fn first() -> u32 {\n    1\n}\n"
)
# R22: the `&self` method precedes the constructor.
SWAPPED = CLEAN.replace(NEW + "\n" + VALUE, VALUE + "\n" + NEW)
# R12: the blank line before the top-level item is missing.
NO_BLANK = CLEAN.replace("}\n\npub fn first", "}\npub fn first")
# Recorded debt at the base: R12 on `pub fn beta`, which the change does not touch.
DEBT = "pub fn alpha() -> u32 {\n    1\n}\npub fn beta() -> u32 {\n    2\n}\n"
# A plural directory with a Rust file at the base: its name is recorded debt (R1).
WIDGET = "pub fn existing() -> u32 {\n    4\n}\n"
REACH = "pub fn reach() -> u32 {\n    super::super::first()\n}\n"
WIDGETS = "pub fn widget() -> u32 {\n    3\n}\n"
GENERATED = "// @generated by a fixture generator\n\npub fn one() -> u32 {\n    1\n}\npub fn two() -> u32 {\n    2\n}\n"
REGENERATED = GENERATED.replace("    2\n", "    3\n")
ENTRY = "pub fn entry() -> u32 {\n    6\n}\n"
# A plural module declaration is recorded debt (R1) wherever the base holds it.
MOD_ITEMS = "pub mod items;\n\n"
OUTER = "pub fn outer() -> u32 {\n    7\n}\n"
GROUP = "pub fn group() -> u32 {\n    8\n}\n"


def run_git(root, *args):
    completed = subprocess.run(
        ["git", "-c", "commit.gpgsign=false", *args],
        cwd=root,
        env=ENV,
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def write(root, files):
    for relative, content in files.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content, encoding="utf-8")


def commit(root, files, message):
    write(root, files)
    run_git(root, "add", "-A")
    run_git(root, "commit", "-q", "-m", message)


def make_repo(test):
    """A repository whose base commit carries the pinned tooling and recorded debt."""
    # Scratch lives under the checkout's git-ignored .orbit/tmp, not the system temp directory.
    scratch_root = ROOT / ".orbit/tmp"
    scratch_root.mkdir(parents=True, exist_ok=True)
    scratch = tempfile.TemporaryDirectory(prefix="source-style-gate.", dir=scratch_root)
    test.addCleanup(scratch.cleanup)
    root = Path(scratch.name)
    run_git(root, "init", "-q")
    commit(
        root,
        {
            ".gitignore": ".orbit/\n",
            "Cargo.toml": CARGO,
            "rustfmt.toml": (ROOT / "rustfmt.toml").read_bytes(),
            "desktop/rustfmt.toml": (ROOT / "desktop/rustfmt.toml").read_bytes(),
            "scripts/check-source-style.py": (SCRIPTS / "check-source-style.py").read_bytes(),
            WRAPPER: (SCRIPTS / "check-source-style-diff.py").read_bytes(),
            "src/lib.rs": LIB,
            "src/clean.rs": CLEAN,
            "src/debt.rs": DEBT,
            "src/widgets/existing.rs": WIDGET,
        },
        "base",
    )
    return root, run_git(root, "rev-parse", "HEAD")


def base_with_declaration(test):
    """A base whose `src/outer.rs` declares a plural module and `src/group/mod.rs` does not."""
    root, _ = make_repo(test)
    commit(root, {"src/outer.rs": MOD_ITEMS + OUTER, "src/group/mod.rs": GROUP}, "declare a module")
    return root, run_git(root, "rev-parse", "HEAD")


def gate(root, base):
    env = dict(ENV, CI_TEST_BASE=base)
    return subprocess.run(
        [sys.executable, WRAPPER], cwd=root, env=env, capture_output=True, text=True
    )


class SourceStyleDiffGate(unittest.TestCase):
    def test_change_beside_recorded_debt_passes(self):
        root, base = make_repo(self)
        # The new function has a blank line before it, so the recorded R12 on
        # `beta` is the only finding in the changed file.
        commit(root, {"src/debt.rs": DEBT + "\npub fn gamma() -> u32 {\n    3\n}\n"}, "add a function")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("no new findings", result.stdout)
        self.assertIn("in 1 changed Rust file(s)", result.stdout)

    def test_new_finding_beside_recorded_debt_fails(self):
        root, base = make_repo(self)
        commit(root, {"src/debt.rs": DEBT + "pub fn gamma() -> u32 {\n    3\n}\n"}, "add a function")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/debt.rs:7: R12", result.stderr)

    def test_seeded_blank_line_fails_and_corrected_passes(self):
        root, base = make_repo(self)
        commit(root, {"src/clean.rs": NO_BLANK}, "seed a blank-line violation")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/clean.rs:", result.stderr)
        self.assertIn("R12", result.stderr)
        commit(root, {"src/clean.rs": CLEAN}, "correct the blank line")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_seeded_impl_order_fails_and_corrected_passes(self):
        root, base = make_repo(self)
        commit(root, {"src/clean.rs": SWAPPED}, "seed an impl-order violation")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/clean.rs:", result.stderr)
        self.assertIn("R22", result.stderr)
        commit(root, {"src/clean.rs": CLEAN}, "correct the impl order")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_seeded_names_and_super_super_fail(self):
        root, base = make_repo(self)
        commit(root, {"src/reach.rs": REACH, "src/widgets.rs": WIDGETS}, "seed R26 and R1")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/reach.rs:2: R26", result.stderr)
        self.assertIn("src/widgets.rs: R1", result.stderr)

    def test_new_file_in_recorded_plural_directory_passes(self):
        root, base = make_repo(self)
        commit(root, {"src/widgets/new.rs": "pub fn added() -> u32 {\n    5\n}\n"}, "add a file")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_existing_debt_moved_by_rename_is_not_new(self):
        root, base = make_repo(self)
        run_git(root, "mv", "src/debt.rs", "src/ledger.rs")
        commit(root, {"src/lib.rs": LIB.replace("mod debt;", "mod ledger;")}, "rename the debt file")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("no new findings", result.stdout)

    def test_directory_moved_to_new_parent_is_not_new(self):
        root, base = make_repo(self)
        (root / "src/nested").mkdir()
        run_git(root, "mv", "src/widgets", "src/nested/widgets")
        commit(root, {}, "move the directory under a new parent")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("no new findings", result.stdout)

    def test_directory_moved_and_duplicated_fails(self):
        root, base = make_repo(self)
        (root / "src/nested").mkdir()
        run_git(root, "mv", "src/widgets", "src/nested/widgets")
        commit(root, {"src/other/widgets/copy.rs": "pub fn copy() -> u32 {\n    9\n}\n"}, "move and add")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/other/widgets/: R1", result.stderr)

    def test_directory_renamed_to_a_plural_fails(self):
        root, _ = make_repo(self)
        commit(root, {"src/gadget/entry.rs": ENTRY}, "add a singular directory")
        base = run_git(root, "rev-parse", "HEAD")
        run_git(root, "mv", "src/gadget", "src/gadgets")
        commit(root, {}, "pluralise the directory")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/gadgets/: R1", result.stderr)

    def test_directory_renamed_to_another_plural_fails(self):
        root, base = make_repo(self)
        run_git(root, "mv", "src/widgets", "src/gadgets")
        commit(root, {}, "rename the plural directory")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/gadgets/: R1", result.stderr)

    def test_directory_findings_beyond_the_base_count_fail(self):
        root, base = make_repo(self)
        commit(root, {"src/gadgets/entry.rs": ENTRY}, "add a plural directory")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/gadgets/: R1", result.stderr)

    def test_module_declaration_moved_into_existing_mod_rs_is_not_new(self):
        root, base = base_with_declaration(self)
        commit(root, {"src/outer.rs": OUTER, "src/group/mod.rs": MOD_ITEMS + GROUP}, "move the declaration")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("no new findings", result.stdout)

    def test_module_declaration_without_base_counterpart_fails(self):
        root, base = base_with_declaration(self)
        commit(root, {"src/group/mod.rs": "pub mod entries;\n\n" + GROUP}, "declare another module")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/group/mod.rs:1: R1", result.stderr)

    def test_edited_module_declaration_fails(self):
        root, base = base_with_declaration(self)
        commit(
            root,
            {"src/outer.rs": OUTER, "src/group/mod.rs": "pub(crate) mod items;\n\n" + GROUP},
            "move and edit the declaration",
        )
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/group/mod.rs:1: R1", result.stderr)

    def test_module_declaration_moved_and_duplicated_fails(self):
        root, base = base_with_declaration(self)
        commit(
            root,
            {
                "src/outer.rs": OUTER,
                "src/group/mod.rs": MOD_ITEMS + GROUP,
                "src/debt.rs": MOD_ITEMS + DEBT,
            },
            "move the declaration and copy it",
        )
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertEqual(result.stderr.count(": R1:"), 1, result.stderr)

    def test_module_renamed_to_a_plural_fails(self):
        root, _ = make_repo(self)
        commit(root, {"src/outer.rs": "pub mod item;\n\n" + OUTER}, "declare a singular module")
        base = run_git(root, "rev-parse", "HEAD")
        commit(root, {"src/outer.rs": MOD_ITEMS + OUTER}, "pluralise the module")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/outer.rs:1: R1", result.stderr)

    def test_inline_module_rename_cannot_spend_unrelated_removed_debt(self):
        root, _ = make_repo(self)
        singular = "pub mod item {\n    pub fn live() {}\n}\n"
        unrelated = "pub mod items {\n    pub fn old() {}\n}\n"
        commit(root, {"src/outer.rs": singular, "src/group/mod.rs": unrelated}, "add modules")
        base = run_git(root, "rev-parse", "HEAD")
        commit(
            root,
            {"src/outer.rs": singular.replace("mod item {", "mod items {"), "src/group/mod.rs": ""},
            "rename a module and remove unrelated debt",
        )
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/outer.rs:1: R1", result.stderr)

    def test_generated_source_is_exempt(self):
        root, base = make_repo(self)
        commit(root, {"src/generated.rs": GENERATED}, "add a generated file")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_generated_only_plural_directory_gaining_source_fails(self):
        root, _ = make_repo(self)
        commit(root, {"src/gadgets/model.rs": GENERATED}, "add a generated-only directory")
        base = run_git(root, "rev-parse", "HEAD")
        commit(root, {"src/gadgets/entry.rs": ENTRY}, "add the first handwritten source")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("src/gadgets/: R1", result.stderr)

    def test_generated_sources_in_plural_directory_stay_exempt(self):
        root, _ = make_repo(self)
        commit(root, {"src/gadgets/model.rs": GENERATED}, "add a generated-only directory")
        base = run_git(root, "rev-parse", "HEAD")
        commit(
            root,
            {"src/gadgets/model.rs": REGENERATED, "src/gadgets/other.rs": GENERATED},
            "regenerate the directory",
        )
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("no new findings", result.stdout)

    def test_corrected_singular_directory_passes(self):
        root, _ = make_repo(self)
        commit(root, {"src/gadgets/model.rs": GENERATED}, "add a generated-only directory")
        base = run_git(root, "rev-parse", "HEAD")
        commit(root, {"src/gadget/entry.rs": ENTRY}, "add the first source in the singular")
        result = gate(root, base)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_edited_pinned_checker_fails(self):
        root, base = make_repo(self)
        edited = (SCRIPTS / "check-source-style.py").read_text(encoding="utf-8") + "\n# local edit\n"
        commit(root, {"scripts/check-source-style.py": edited}, "edit the checker")
        result = gate(root, base)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("pinned", result.stderr)

    def test_unresolved_base_fails(self):
        root, _ = make_repo(self)
        result = gate(root, "0" * 40)
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("source-style diff:", result.stderr)

    def test_snapshot_is_removed(self):
        root, base = make_repo(self)
        commit(root, {"src/clean.rs": NO_BLANK}, "seed a blank-line violation")
        gate(root, base)
        self.assertEqual(list((root / ".orbit/tmp").glob("source-style.*")), [])


if __name__ == "__main__":
    unittest.main()
